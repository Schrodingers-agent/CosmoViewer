"""
scripts.py — "export as script".

script_for() writes a short, standalone Python script that recomputes an
Analyses result headlessly with the same calls the window made, and writes
the same CSV the Export button writes. Running it must reproduce the window's
numbers exactly (test_analyses_window_profiles_energy.py runs one and compares).
"""
from __future__ import annotations

import os

_HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

_HEAD = '''"""Reproduces "{title}" from the CosmoViewer Explorer.
Generated by measurements.scripts; edit freely."""
import sys
sys.path.insert(0, {explorer!r})        # the Dataset Explorer folder

import numpy as np
from measurements import SnapshotView, find_centre, lagrangian_radii

SNAPSHOT = {snapshot!r}
TYPES = {types!r}                       # particle types
FRAME = {frame!r}
CENTRE = {centre!r}
SELECTION_SET = {selection!r}           # a selection-set file, or None
OUT = {out!r}

view = SnapshotView(SNAPSHOT)
'''

_SET = '''

def restrict(p):
    if SELECTION_SET is None:
        return p
    import selection_sets
    s = selection_sets.read_set(SELECTION_SET)
    keep = np.isin(np.asarray(p.ids).astype(np.uint64), np.asarray(s.ids, dtype=np.uint64))
    sub = p.subset(keep)
    return sub

'''

_BODIES = {
    "lagrangian": '''
p = restrict(view.particles(TYPES, frame=FRAME, velocities=False, ids=SELECTION_SET is not None))
c = find_centre(p, CENTRE)
res = lagrangian_radii(p, c)
table = np.column_stack([res["fraction"], res["radius"].value, res["radius_err_sampling"].value])
names = ["mass fraction", "radius [kpc]", "sampling error [kpc]"]
''',
    "profile": '''from measurements.profiles import radial_profile

p = restrict(view.particles(TYPES, frame=FRAME, velocities=True, ids=SELECTION_SET is not None))
if p.vel is not None and np.isnan(p.vel).any():
    p.vel = None
c = find_centre(p, CENTRE)
r10 = float(lagrangian_radii(p, c, [0.10])["radius"].value[0])
if p.vel is not None:
    c = find_centre(p, CENTRE, velocity_radius=r10)   # centre velocity inside r_10
soft = max((s for s in (view.softening(t)[0] for t in TYPES) if s), default=None)
if FRAME == "comoving" and soft:
    soft = soft / view.a
res = radial_profile(p, c, n_bins={n_bins}, softening=soft)
cols = [("r_lo [kpc]", res["r_lo"].value), ("r_hi [kpc]", res["r_hi"].value),
        ("r_mean [kpc]", res["r_mean"].value), ("N", res["n"].astype(float)),
        ("density [Msun/kpc3]", res["density"].value), ("density err", res["density_err"].value),
        ("M(<r_hi) [Msun]", res["mass_enclosed"].value), ("v_circ [km/s]", res["v_circ"].value),
        ("sigma_r [km/s]", res["sigma_r"].value), ("sigma_r err", res["sigma_r_err"].value),
        ("sigma_t [km/s]", res["sigma_t"].value), ("sigma_t err", res["sigma_t_err"].value),
        ("beta", res["beta"]), ("beta err", res["beta_err"]),
        ("resolved", res["resolved"].astype(float))]
table = np.column_stack([v for _, v in cols])
names = [k for k, _ in cols]
''',
    "energy": '''from measurements.energy import energy_budget

ids = None
if SELECTION_SET is not None:
    import selection_sets
    ids = selection_sets.read_set(SELECTION_SET).ids
res = energy_budget(view, TYPES, ids=ids)
v = lambda k: float(np.asarray(getattr(res[k], "value", res[k])))
table = np.array([[v("K"), 0], [v("U"), 0], [v("W"), v("W_err")], [v("E"), v("W_err")],
                  [v("Q"), v("Q_err")]])
names = ["value", "error"]                # rows: K, U, W, E, Q
''',
    "sanity": '''from measurements.sanity import sanity_report

res = sanity_report(view, TYPES)
print(res.to_text())
table = np.array([[c.count] for c in res.checks], dtype=float)
names = ["particles affected"]            # one row per check, in report order
''',
}

_TAIL = '''
print(res.provenance.status_line() if hasattr(res, "provenance") else "")
np.savetxt(OUT, table, delimiter=",", header=",".join(n.replace(",", " ") for n in names),
           comments="", fmt="%.10e")
print("wrote", OUT)
'''


def script_for(kind: str, *, title: str, snapshot: str, types, frame: str = "physical",
               centre: str = "shrinking_sphere", selection: str | None = None,
               out: str = "result.csv", n_bins: int = 30) -> str:
    """Python source that recomputes one Analyses result. kind: lagrangian,
    profile, energy or sanity."""
    if kind not in _BODIES:
        raise ValueError(f"kind must be one of {sorted(_BODIES)}")
    head = _HEAD.format(title=title, explorer=_HERE, snapshot=str(snapshot),
                        types=[int(t) for t in types], frame=frame, centre=centre,
                        selection=selection, out=out)
    return head + _SET + _BODIES[kind].format(n_bins=n_bins) + _TAIL
